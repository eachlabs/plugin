#!/usr/bin/env bash
# Regenerates skills/ from a checkout of eachlabs/skills and reports what changed.
#
# Usage: scripts/sync-skills.sh <eachlabs/skills checkout> <report dir>
#
# Exits 1 when the conversion is incomplete (a TODO(contract) line, a call with no
# tool, or a rewrite anchor the source no longer contains), so a half-converted
# skill is never proposed. Writes to <report dir>:
#   convert.log  the converter's output
#   changed      "yes" or "no"
#   summary.md   the source commit, a table of added, changed and removed skills,
#                and the converter's summary lines
set -euo pipefail

src="$1"
report="$2"
mkdir -p "$report"
commit="$(git -C "$src" rev-parse HEAD)"

# Regenerate from scratch so a skill removed upstream disappears here too.
rm -rf skills
node scripts/convert-skills.mjs --source "$src" --out skills > "$report/convert.log"

problems="$(grep -E 'TODO\(contract\): [1-9]|no tool for|anchor not found' "$report/convert.log" || true)"
if [ -n "$problems" ]; then
  echo "::error::The conversion is incomplete; scripts/convert-skills.mjs needs updating for eachlabs/skills ${commit:0:7}."
  echo "$problems"
  exit 1
fi

node scripts/check-skills.mjs

# DEFERRED.md records the source commit, so a new upstream commit that changes no
# skill still rewrites that one line. That alone is not a change worth a PR.
if git diff --quiet -I '^Generated by ' -- skills/DEFERRED.md; then
  git checkout -- skills/DEFERRED.md
fi

if [ -z "$(git status --porcelain -- skills)" ]; then
  echo "no" > "$report/changed"
  echo "Nothing changed: skills/ already matches eachlabs/skills ${commit:0:7}."
  exit 0
fi
echo "yes" > "$report/changed"

{
  echo "Source: [eachlabs/skills@${commit:0:7}](https://github.com/eachlabs/skills/commit/${commit})"
  echo
  echo "| Skill | Change |"
  echo "| --- | --- |"
  git status --porcelain --untracked-files=all -- skills \
    | awk '{print $NF}' \
    | cut -d/ -f2 \
    | sort -u \
    | while read -r name; do
        if [ "$name" = "DEFERRED.md" ]; then
          echo "| \`DEFERRED.md\` | list of skills not converted |"
        elif ! git cat-file -e "HEAD:skills/$name" 2>/dev/null; then
          echo "| \`$name\` | added |"
        elif [ ! -e "skills/$name" ]; then
          echo "| \`$name\` | removed |"
        else
          echo "| \`$name\` | changed |"
        fi
      done
  echo
  echo "Converter summary:"
  echo
  echo '```'
  grep -E '^(converted|deferred|skipped|TODO\(contract\)|notes):' "$report/convert.log"
  echo '```'
} > "$report/summary.md"
cat "$report/summary.md"
